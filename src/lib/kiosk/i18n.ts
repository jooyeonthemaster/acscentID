export const KIOSK_TEXT: Record<KioskLang, KioskText> = {
  ko,
  en,
  ja,
  'zh-Hans': zhHans,
  'zh-Hant': zhHant,
}

export function kioskText(lang: KioskLang): KioskText {
  return KIOSK_TEXT[lang] ?? ko
}

/** 분석 API에 넘길 사이트 로케일 — 번체는 사이트에 없어 zh 로 만들고 번체 지시를 덧붙인다 */
export function analysisLocale(lang: KioskLang): { locale: 'ko' | 'en' | 'ja' | 'zh'; traditional: boolean } {
  if (lang === 'zh-Hans') return { locale: 'zh', traditional: false }
  if (lang === 'zh-Hant') return { locale: 'zh', traditional: true }
  return { locale: lang, traditional: false }
}
