/**
 * 키오스크 다국어 — 한국어 · English · 日本語 · 简体中文 · 繁體中文
 *
 * 한국어(ko)가 원본이고 KioskText = typeof ko 다. 나머지 언어는 이 타입을 그대로
 * 채워야 하므로, 한국어에 문구를 추가하고 번역을 빠뜨리면 타입 에러가 난다
 * (= "번역 안 된 곳" 이 빌드 단계에서 잡힌다).
 *
 * 번역 대상이 아닌 것
 * - 이미 영어인 라벨 (STEP, NAME, GENDER, SIGNALS, PRECAUTION …)
 * - 매장 스태프 전용 화면 (관리자 패널, 설정 오류 경고) — 스태프는 한국어를 쓴다
 * - 숨김 처리된 프로그램(사주·내 이미지) 전용 화면
 * AI가 쓰는 분석 문장과 향수 이름·노트는 여기가 아니라 분석 API가 해당 언어로 만든다.
 */

export type KioskLang = 'ko' | 'en' | 'ja' | 'zh-Hans' | 'zh-Hant'

export const KIOSK_LANGS: { id: KioskLang; label: string; code: string; htmlLang: string }[] = [
  { id: 'ko', label: '한국어', code: 'KO', htmlLang: 'ko' },
  { id: 'en', label: 'English', code: 'EN', htmlLang: 'en' },
  { id: 'ja', label: '日本語', code: 'JA', htmlLang: 'ja' },
  { id: 'zh-Hans', label: '简体中文', code: '简', htmlLang: 'zh-Hans' },
  { id: 'zh-Hant', label: '繁體中文', code: '繁', htmlLang: 'zh-Hant' },
]

export function isKioskLang(value: unknown): value is KioskLang {
  return typeof value === 'string' && KIOSK_LANGS.some((l) => l.id === value)
}

/** 한자권 글꼴이 필요한 언어 — 테마의 한국어 전용 글꼴로는 글리프가 없다 */
export function isCjkLang(lang: KioskLang): lang is 'ja' | 'zh-Hans' | 'zh-Hant' {
  return lang === 'ja' || lang === 'zh-Hans' || lang === 'zh-Hant'
}

