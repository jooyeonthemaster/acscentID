const BY_KEY = new Map(CAREER_COMBOS.map((c) => [c.key, c]))

/** 점수 순서의 축(exploreCareers 의 axes)에서 1위 × 2위 풀이를 고른다 */
export function pickCareerCombo(axes: readonly CareerAxis[]): CareerCombo {
  const [primary, secondary] = axes
  const found = BY_KEY.get(`${primary}-${secondary}`)
  if (!found) throw new Error(`축 조합 풀이가 없습니다: ${primary}-${secondary}`)
  return found
}
