export const BOOTH_TEXT: Record<BoothLang, BoothText> = {
  ko,
  en,
  ja,
  'zh-Hans': zhHans,
  'zh-Hant': zhHant,
}

export function boothText(lang: BoothLang): BoothText {
  return BOOTH_TEXT[lang] ?? ko
}

/** 손님 폰 페이지 ?lang= — 없거나 모르는 값이면 한국어 */
/** 흔히 쓰는 다른 언어 코드 — 손님이 주소를 직접 고치거나 다른 곳에서 링크를 만들어도 알아듣게(부스 QR 은 zh-Hans·zh-Hant 를 쓴다) */
const LANG_ALIASES: Record<string, BoothLang> = {
  zh: 'zh-Hans', 'zh-cn': 'zh-Hans', 'zh-sg': 'zh-Hans', 'zh-hans': 'zh-Hans',
  'zh-tw': 'zh-Hant', 'zh-hk': 'zh-Hant', 'zh-mo': 'zh-Hant', 'zh-hant': 'zh-Hant',
  'ja-jp': 'ja', jp: 'ja', 'en-us': 'en', 'en-gb': 'en', 'ko-kr': 'ko', kr: 'ko',
}

export function parseBoothLang(value: unknown): BoothLang {
  const v = Array.isArray(value) ? value[0] : value
  if (isBoothLang(v)) return v
  return typeof v === 'string' ? LANG_ALIASES[v.trim().toLowerCase().replace('_', '-')] ?? 'ko' : 'ko'
}

/** 부스가 만드는 손님 폰 QR 주소에 언어를 붙인다(한국어는 붙이지 않는다) */
export function withBoothLang(url: string, lang: BoothLang): string {
  if (lang === 'ko') return url
  return `${url}${url.includes('?') ? '&' : '?'}lang=${encodeURIComponent(lang)}`
}

/** 화면에 보일 AI 아이돌 컨셉 이름·설명 */
export function conceptText(t: BoothText, concept: { id: string; name: { ko: string }; desc: { ko: string } }): Named {
  return t.concepts[concept.id] ?? { name: concept.name.ko, desc: concept.desc.ko }
}

/** 화면에 보일 인화 디자인 이름(인화물 위 글씨는 바꾸지 않는다) */
export function designName(t: BoothText, design: { id: string; kind: string; name: { ko: string } }): string {
  return t.designs[design.id] ?? t.designKinds[design.kind] ?? design.name.ko
}

/** 대기 화면 제목 — 사전에 없는 운영 모드는 한국어면 headline, 그 밖은 영어 줄 */
export function attractHeadline(
  t: BoothText,
  lang: BoothLang,
  mode: { id: string; attract?: { headline: string; headlineEn?: string } }
): string {
  const known = t.attract[mode.id]
  if (known) return known
  if (!mode.attract) return ''
  return lang === 'ko' ? mode.attract.headline : mode.attract.headlineEn ?? mode.attract.headline
}

/**
 * 이용권 확인 실패 안내 — 한국어는 서버 문구 그대로(사용 기한 날짜 등이 들어 있다),
 * 다른 언어는 응답 상태·제목으로 종류를 가려 번역 문구를 쓴다(/api/photobooth/pass).
 */
export function passErrorText(lang: BoothLang, status: number, server: { title?: unknown; error?: unknown }): PassError {
  const t = boothText(lang)
  const title = typeof server.title === 'string' ? server.title : ''
  const error = typeof server.error === 'string' ? server.error : ''
  if (lang === 'ko') return { title: title || t.passFailTitle, message: error || t.passFailMessage }
  const kind =
    status === 429 ? 'rateLimit'
      : status === 404 ? 'notFound'
        : status === 410 ? (title.includes('시간') || error.includes('기간') ? 'expired' : title.includes('취소') ? 'cancelled' : 'used')
          : null
  return kind ? t.passErrors[kind] : { title: t.passFailTitle, message: t.passFailMessage }
}

/**
 * 손님에게 보일 오류 문구 — 한국어 화면은 원래 문구 그대로, 다른 언어는 한글 문구(서버·기기 오류)면 fallback 으로.
 * (이 파일 사전에서 나온 문구는 이미 그 언어라 그대로 보인다)
 */
export function guestError(lang: BoothLang, message: string | null | undefined, fallback: string): string {
  if (!message) return fallback
  if (lang === 'ko') return message
  return /[\uAC00-\uD7A3]/.test(message) ? fallback : message
}
